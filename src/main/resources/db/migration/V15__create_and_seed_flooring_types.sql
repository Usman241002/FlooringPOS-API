CREATE TABLE flooring_types
(
    id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id            INTEGER        NOT NULL REFERENCES categories (id),
    name                   VARCHAR(100)   NOT NULL,
    thickness_mm           INTEGER,
    fitting_price_m2       NUMERIC(12, 2) NOT NULL
        CHECK (fitting_price_m2 >= 0),
    minimum_fitting_charge NUMERIC(12, 2) NOT NULL
        CHECK (minimum_fitting_charge >= 0),
    UNIQUE (category_id, name)
);

INSERT INTO flooring_types (category_id,
                            name,
                            thickness_mm,
                            fitting_price_m2,
                            minimum_fitting_charge)
SELECT c.id,
       v.name,
       v.thickness_mm,
       v.fitting_price_m2,
       v.minimum_fitting_charge

FROM (VALUES ('Carpet', 'Standard', NULL::INTEGER, 2.50::NUMERIC, 35.00::NUMERIC),
             ('Lino', 'Standard', NULL::INTEGER, 2.50::NUMERIC, 35.00::NUMERIC),

             ('Laminate', '7mm Standard', 7, 6.00, 70.00),
             ('Laminate', '8mm Standard', 8, 6.00, 70.00),
             ('Laminate', '10mm Standard', 10, 6.00, 70.00),
             ('Laminate', '12mm Standard', 12, 6.00, 70.00),
             ('Laminate', '12mm Herringbone', 12, 15.00, 110.00),

             ('SPC', 'Standard', NULL::INTEGER, 7.00, 70.00),
             ('SPC', 'Herringbone', NULL::INTEGER, 15.00, 110.00)) AS v(category_name, name, thickness_mm,
                                                                        fitting_price_m2, minimum_fitting_charge)
         JOIN categories c ON LOWER(c.name) = LOWER(v.category_name)
ON CONFLICT (category_id, name) DO NOTHING;