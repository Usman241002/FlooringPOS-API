CREATE TABLE rooms
(
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    address_id INTEGER      NOT NULL,

    name       VARCHAR(150) NOT NULL,

    length_m   NUMERIC(10, 3),
    width_m    NUMERIC(10, 3),

    CONSTRAINT fk_rooms_address
        FOREIGN KEY (address_id)
            REFERENCES addresses (id)
            ON DELETE CASCADE,

    CONSTRAINT chk_rooms_length_positive
        CHECK (length_m IS NULL OR length_m > 0),

    CONSTRAINT chk_rooms_width_positive
        CHECK (width_m IS NULL OR width_m > 0)
);